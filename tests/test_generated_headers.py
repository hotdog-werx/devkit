from pathlib import Path

import pytest
from repolish.testing import make_context


@pytest.mark.parametrize(
    ('member_name', 'expected_slug'),
    [
        ('_root', None),
        ('', None),
        ('package-a', 'package-a'),
    ],
)
def test_generated_header_uses_provider_metadata(
    member_name,
    expected_slug,
) -> None:
    """The standard header identifies the provider version and optional workspace member."""
    repolish_context = make_context(version='1.2.3', project_name='devkit-workspace')
    repolish_context.provider.session.member_name = member_name
    slug = 'devkit-workspace(in package-a)' if expected_slug else 'devkit-workspace'

    assert repolish_context.generated_header == (f'generated by {slug}@1.2.3 - manual changes may be overwritten')


def test_managed_workflow_templates_share_generated_header() -> None:
    """Every provider-managed workflow delegates its header to the standard field."""
    packages_dir = Path(__file__).parents[1] / 'packages'
    workflow_templates = list(
        packages_dir.glob(
            'devkit-*/devkit/*/resources/templates/repolish/.github/workflows/*.jinja',
        )
    )

    assert len(workflow_templates) == 5
    assert all(
        template.read_text(encoding='utf-8').splitlines()[0] == '# {{ repolish.generated_header }}'
        for template in workflow_templates
    )
